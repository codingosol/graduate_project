-- 정치 비율이 낮은 outlet(SBS 9.5% / KBS 3.8% / YTN 5.8%)을 보강하려고
-- 각 언론사의 시사 전문 채널(SBS 시사교양 라디오 70%, KBS시사 46%, YTN 시사 48%)을 추가하면서,
-- 스트레이트 뉴스 채널과 시사/논평 채널을 구분할 수 있도록 채널 종류를 기록한다.
--
-- 왜 필요한가: 논평 프로그램의 댓글 여론은 스트레이트 뉴스 댓글보다 당파적일 가능성이 높음.
-- 둘을 섞어서 집계하면 "언론사의 정치 성향"이 아니라 "장르 차이"를 재게 될 위험이 있음.
-- 데이터는 한 번만 넓게 모아두고, 분석 단계에서 news만 / opinion만 / 전체 세 가지로
-- 각각 집계해 비교할 수 있게 컬럼으로 남겨둔다.
--
-- news    : 스트레이트 뉴스 채널 (기존 10개 채널 전부)
-- opinion : 시사·논평·토론·라디오 프로그램 채널 (이번에 추가하는 3개)
--   ※ 오마이TV는 기존 채널이지만 실제로는 논평 성격이 강함(정치 비율 89.5%).
--     장르 재분류가 필요한지는 분석 단계에서 따로 판단할 것.

ALTER TABLE channels ADD COLUMN channel_type TEXT NOT NULL DEFAULT 'news'
    CHECK (channel_type IN ('news', 'opinion'));
